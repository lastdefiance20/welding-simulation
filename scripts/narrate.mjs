// Narration: one audio file per line, through OpenRouter's text-to-speech (/api/v1/audio/speech).
//   node scripts/narrate.mjs --project example-robot --lang ko [--only id,id] [--force]
// The project's narration.js exports `voice` ({ model, voice, speed? }) and `lines(lang)` -> [{ id, text }].
// Files go to projects/<id>/narration/<lang>/<line>.mp3 with an index.js the project imports (durations, so its
// timeline can make room). A line is regenerated only when its text, model or voice changed (or --only / --force).
// The key is OPENROUTER_API_KEY, from the environment or the repo's .env.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
const project = arg('project'), lang = arg('lang', 'en');
const only = arg('only', '') ? arg('only').split(',') : null, force = process.argv.includes('--force');
if (!project) { console.error('--project <id> required'); process.exit(1); }

function apiKey() {
  if (process.env.OPENROUTER_API_KEY) return process.env.OPENROUTER_API_KEY;
  const env = path.join(ROOT, '.env');
  if (fs.existsSync(env)) {
    const m = fs.readFileSync(env, 'utf8').match(/^\s*OPENROUTER_API_KEY\s*=\s*"?([^"\n]+)"?/m);
    if (m) return m[1].trim();
  }
  throw new Error('OPENROUTER_API_KEY not set (environment or .env)');
}

const spec = await import(path.join(ROOT, 'projects', project, 'narration.js'));
const { model, voice, speed } = spec.voice;
const lines = spec.lines(lang);
const dir = path.join(ROOT, 'projects', project, 'narration', lang);
fs.mkdirSync(dir, { recursive: true });
const indexFile = path.join(dir, 'index.js');
const prev = fs.existsSync(indexFile) ? (await import(indexFile + '?' + Date.now())).default : {};

const out = {};
for (const { id, text } of lines) {
  const hash = crypto.createHash('sha1').update(JSON.stringify([model, voice, speed ?? 1, text])).digest('hex').slice(0, 10);
  const file = `${id}.mp3`, full = path.join(dir, file);
  const fresh = prev[id]?.hash === hash && fs.existsSync(full);
  if (fresh && !force && !(only && only.includes(id))) { out[id] = prev[id]; continue; }
  if (only && !only.includes(id) && fresh) { out[id] = prev[id]; continue; }
  process.stdout.write(`${id}: ${text}\n`);
  const res = await fetch('https://openrouter.ai/api/v1/audio/speech', {
    method: 'POST',
    headers: { Authorization: `Bearer ${apiKey()}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ model, voice, input: text, response_format: 'mp3', ...(speed ? { speed } : {}) }),
  });
  if (!res.ok) throw new Error(`${id}: ${res.status} ${await res.text()}`);
  fs.writeFileSync(full, Buffer.from(await res.arrayBuffer()));
  const dur = +execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', full]).toString().trim();
  out[id] = { file, text, hash, dur: +dur.toFixed(3) };
}
// Lines no longer in the script: drop their files.
for (const id of Object.keys(prev)) if (!out[id]) { fs.rmSync(path.join(dir, prev[id].file), { force: true }); console.log(`removed ${id}`); }
fs.writeFileSync(indexFile, `// Generated by scripts/narrate.mjs. Do not edit: change the text in narration.js and rerun.\nexport default ${JSON.stringify(out, null, 2)};\n`);
const total = Object.values(out).reduce((s, l) => s + l.dur, 0);
console.log(`${Object.keys(out).length} lines, ${total.toFixed(1)} s of speech -> ${path.relative(ROOT, dir)}`);
